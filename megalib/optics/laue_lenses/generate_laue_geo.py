#!/usr/bin/env python3
"""Generate the MEGAlib geometry section for the PHEMTO Laue lens.

The crystal layout mirrors run/tmp/make_ring_source.py: Si(111) tiles on
concentric rings, one ring per energy, at z = focal. For each ring:
    theta_b = arcsin(hc / (2 d_hkl E))        Bragg angle
    r       = focal * tan(2 theta_b)          ring radius [cm]
    N       = int(2 pi r / l_nf)              number of crystals

Each tile is a Silicon BRIK with the radial size = l_f and the tangential
size = l_nf, lying flat in the lens plane and rotated about z so its long
(radial) side points outward. Output goes to ../PHEMTO_LaueLens.geo.

Notes
-----
* The tiles are kept flat (no per-crystal Bragg tilt): MEGAlib does not
  simulate Bragg diffraction, so this is a passive mass/visualization model;
  the diffraction is handled by the ring sources in make_ring_source.py.
* Positions use endpoint=False to avoid the first/last tile overlapping
  (make_ring_source.py currently uses linspace endpoint=True, which places a
  duplicate tile at phi=0; worth aligning there too).
"""
import os
import numpy as np

# --- constants (keep in sync with make_ring_source.py) ------------------
E_list = [50.0, 51.0, 52.0, 53.0, 54.1, 55.2, 56.4, 57.6, 58.9, 60.2, 61.6, 63.1, 64.6, 66.2, 67.9, 69.7, 71.6, 73.6, 75.7, 77.9, 80.3, 82.8, 85.5, 88.4, 91.4, 94.7, 98.2, 102.0, 106.1, 110.6, 115.4, 120.7, 126.4, 132.8, 139.8, 147.7, 156.4, 166.3, 177.5, 190.3, 205.0, 222.3, 242.8, 267.4, 297.6, 335.4, 384.3, 449.8]

d_hkl = 3.135                  # A, Si(111) lattice spacing
hc = 12.4                      # A*keV
focal = 2000.0                 # cm, focal length (lens plane at z = focal)
l_f = 3.0                      # cm, focusing (radial) crystal size
l_nf = 1.0                     # cm, non-focusing (tangential) crystal size
thickness = 0.2               # cm, crystal thickness along z (adjustable)

# ROOT color index per ring, matching make_ring_source.py colors
# (blue, red, black, green) -> (4, 2, 1, 3)

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   '..', 'PHEMTO_LaueLens.geo')


def ring_geometry(E):
    theta_b = np.arcsin(hc / (2 * d_hkl * E))
    r = focal * np.tan(2 * theta_b)
    n = int(2 * np.pi * r / l_nf)
    return theta_b, r, n


def main():
    lines = []
    w = lines.append

    w('// =====================================================================')
    w('//  PHEMTO Laue lens  -  Si(111) crystal rings (50, 100, 200, 400 keV)')
    w('//  Auto-generated by optics/laue_lenses/generate_laue_geo.py')
    w('//  Layout follows run/tmp/make_ring_source.py:')
    w(f'//    d_hkl={d_hkl} A (Si 111), hc={hc} A.keV, focal={focal:.0f} cm')
    w(f'//    l_f={l_f} cm (radial), l_nf={l_nf} cm (tangential), '
      f't={thickness} cm')
    w('//')
    w('//  Requires (both present in your instrument setups):')
    w('//    - a "WorldVolume" in the parent setup  (Mother of the tiles)')
    w('//    - the "Silicon" material (Materials_v.geo / Materials.geo)')
    w('//')
    w('//  ATTENTION: the lens sits at z = focal = %.0f cm. Enlarge' % focal)
    w('//  WorldVolume and SurroundingSphere in the parent setup so they')
    w('//  contain it before Include-ing this file.')
    w('// =====================================================================')
    w('')

    total = 0
    for E in E_list:
        theta_b, r, n = ring_geometry(E)
        total += n
        tag = f'{int(E)}keV'
        tmpl = f'LaueXtal_{tag}'

        w('// ---------------------------------------------------------------')
        w(f'//  {E:.0f} keV ring : theta_b={np.degrees(theta_b):.3f} deg, '
          f'r={r:.2f} cm, N={n} crystals')
        w('// ---------------------------------------------------------------')
        # template tile for this ring (carries material/shape/color/visibility)
        w(f'Volume {tmpl}')
        w(f'{tmpl}.Material Silicon')
        w(f'{tmpl}.Shape BRIK {l_f/2:.4f} {l_nf/2:.4f} {thickness/2:.4f}')
        w(f'{tmpl}.Color 4')
        w(f'{tmpl}.Visibility 1')
        w('')

        phi = np.linspace(0, 2 * np.pi, n, endpoint=False)
        x, y = r * np.cos(phi), r * np.sin(phi)
        for i in range(n):
            name = f'LX{int(E)}_{i}'
            w(f'{tmpl}.Copy {name}')
            w(f'{name}.Position {x[i]:.4f} {y[i]:.4f} {focal:.4f}')
            w(f'{name}.Rotation 0 0 {np.degrees(phi[i]):.4f}')
            w(f'{name}.Mother WorldVolume')
        w('')

    with open(OUT, 'w') as fh:
        fh.write('\n'.join(lines) + '\n')

    print(f'Wrote {os.path.normpath(OUT)}')
    print(f'Total crystals: {total}')
    for E in E_list:
        theta_b, r, n = ring_geometry(E)
        print(f'  {E:>4.0f} keV : r={r:8.2f} cm, N={n:4d}, '
              f'2*theta_b={np.degrees(2*theta_b):.3f} deg')


if __name__ == '__main__':
    main()
